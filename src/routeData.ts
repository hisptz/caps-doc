import { defineRouteMiddleware, type StarlightRouteData } from '@astrojs/starlight/route-data';
import { activeTab, tabs } from './tabs';

// Show only the active tab's section in the left menu, like the section tabs in Material for MkDocs.
export const onRequest = defineRouteMiddleware((context) => {
	const route = context.locals.starlightRoute;
	const base = import.meta.env.BASE_URL.replace(/\/$/, '');
	const tab = tabs.find((t) => t.id === activeTab(context.url.pathname.slice(base.length) || '/'));
	if (!tab) return;

	const group = route.sidebar.find((entry) => entry.type === 'group' && entry.label === tab.label);
	if (group?.type !== 'group') return;
	prettifyFolderLabels(group.entries);
	route.sidebar = [group];
});

type SidebarEntry = StarlightRouteData['sidebar'][number];

// Autogenerated groups are labelled with the raw folder name; turn "getting-started" into "Getting started".
function prettifyFolderLabels(entries: SidebarEntry[]) {
	for (const entry of entries) {
		if (entry.type !== 'group') continue;
		entry.label = entry.label.charAt(0).toUpperCase() + entry.label.slice(1).replace(/-/g, ' ');
		prettifyFolderLabels(entry.entries);
	}
}
